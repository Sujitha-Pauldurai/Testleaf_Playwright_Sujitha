// Javascript Program for finding the number is odd or even

function oddOrEven(number){

    if(number%2 ==0){
        console.log("The number "+number+" is Even");
        
    }
    else{
        console.log("The number "+number+"  is odd")
    }
}
oddOrEven(5)
oddOrEven(68)
